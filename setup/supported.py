#!/usr/bin/env python3
"""Writes SUPPORTED.md from tests/rtl_433_samples.jsonl: python3 setup/supported.py

The brand guide at the top is written by hand, here. The table of radio models
is worked out by running our decoder over one recorded rtl_433 line per model,
so it says what we actually read from each, not what we hope to.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from sources import rtl_433   # noqa: E402

# Recordings that went all the way through rtl_433 25.02 and this program on a
# Pi (2026-10-16), not only the decoder: rtl_433_tests file → model.
REPLAYED = {
    "Acurite-Atlas", "Acurite-Tower", "Acurite-6045M", "Acurite-Rain899", "Acurite-5n1",
    "Ambientweather-F007TH", "AmbientWeather-WH31E", "AmbientWeather-WH31B", "Bresser-5in1",
    "EcoWitt-WH40", "Fineoffset-WH1050", "Fineoffset-WH24", "Fineoffset-WS90",
}
REAL_GEAR = {"Acurite-Atlas", "Acurite-Tower"}

SHORT = {"temp_f": "temp", "humidity_pct": "humidity", "wind_mph": "wind", "wind_gust_mph": "gust",
         "wind_dir_deg": "direction", "pressure_inhg": "pressure", "uv_index": "UV", "light_lux": "light",
         "strike_count": "lightning", "last_strike_mi": "strike distance", "battery": "battery"}

HEADER = """# Supported stations

This program started as a way to keep AcuRite data after AcuRite's cloud
change. It can now listen to other brands too, in two ways. **Only AcuRite has
been tried on real hardware.** Everything else below is untested or tested
only against recordings. If yours misreads, run
`python3 acurite-capture.py --diagnostics` and attach the file it writes to an
issue; it carries what your station actually sent.

## How sure we are

- **Real gear**: running in a house, every day.
- **Replayed**: a real radio recording (from the rtl_433 project) went through
  rtl_433 and this program on a Pi, and came out right.
- **Decoder only**: rtl_433's recorded output for that model goes through our
  decoder correctly; the radio side is rtl_433's own and is tested by them.
- **Untested**: written from the published format, never run against the real
  thing.

## 1. Your console uploads to us (no radio needed)

If your console or WiFi gateway has a "custom server" or "Customized" upload
setting, point it at this machine, port 12346, and turn on `[console]` in
config.ini. Your console keeps sending to its own cloud as well.

| Brand | Where the setting is | Protocol to pick | Status |
|---|---|---|---|
| Ambient Weather (WS-2902, WS-2000, WS-5000, their WiFi hubs) | awnet app → Customized | Ambient Weather or Wunderground | Untested |
| Ecowitt (GW1000, GW1100, GW2000, HP2551, ...) | WS View Plus app, or the gateway's web page → Customized | Ecowitt | Untested |
| Fine Offset relabels (Misol, Froggit, Sainlogic, Pantech, ...) | same as Ecowitt | Ecowitt or Wunderground | Untested |
| Anything else that uploads in Weather Underground format | its own settings | Wunderground | Untested |

Readings arrive as `console-outdoor`, `console-indoor`, and `console-ch1` to
`console-ch8`.

## 2. A USB radio dongle hears your sensors directly

An RTL-SDR dongle (the RTL-SDR Blog V4 works) and rtl_433. Set `[capture]`
in config.ini: `enabled = true`, the `frequency` your sensors use, and
`protocols` (the numbers below, from `rtl_433 -R help` in rtl_433 25.02; or
`all`, then `--discover` to see what's near).

One dongle hears one frequency at a time. To hear two bands, list both and set
`hop_seconds`; it misses whatever is sent on the other band meanwhile. A second
dongle is the clean answer.

| Brand family | Frequency | rtl_433 protocols |
|---|---|---|
| AcuRite (Atlas, Iris, 5-in-1, towers) | 433.92M | 40, 74 |
| Ambient Weather / Ecowitt / Fine Offset, North America (WS-2902 array, WH31E, WH40, WS90, ...) | 915M | 78, 113, 213, 244, 142, 190 |
| Same, Europe | 868M | same |
| Ambient Weather F007TH and older 433 MHz sensors | 433.92M | 20, 112 |
| Fine Offset WH1080/WH3080/WH1050 (older all-in-ones, many relabels) | 433.92M (EU 868M) | 32, 69, 155 |
| Bresser 5-in-1, 6-in-1, 7-in-1, Froggit WH6000 | 868M (EU), 915M (US) | 119, 172, 173 |
| La Crosse (TX141, LTV range, WS-2310) | 433.92M or 915M by model | 34, 73, 166, 170, 171, 175 |
| Oregon Scientific | 433.92M | 12 |

## Radio models we read

Generated by `setup/supported.py` from `tests/rtl_433_samples.jsonl`.
"Outdoor" models get an outdoor card on the dashboard; the rest get a room card.

| Model | Card | What we read | How sure |
|---|---|---|---|
"""


def main() -> None:
    rows = []
    for line in (ROOT / "tests" / "rtl_433_samples.jsonl").read_text().splitlines():
        raw = json.loads(line)["line"]
        decoded = rtl_433.decode(raw)
        if decoded is None:
            continue
        _, kind, fields, rain = decoded
        read = [SHORT[k] for k in SHORT if k in fields] + (["rain"] if rain is not None else [])
        model = raw["model"]
        sure = "Real gear" if model in REAL_GEAR else "Replayed" if model in REPLAYED else "Decoder only"
        card = "outdoor" if kind in ("outdoor", "Atlas", "Iris", "5N1") else "room"
        rows.append(f"| {model} | {card} | {', '.join(read)} | {sure} |")
    (ROOT / "SUPPORTED.md").write_text(HEADER + "\n".join(rows) + "\n")
    print(f"SUPPORTED.md: {len(rows)} radio models")


if __name__ == "__main__":
    main()
